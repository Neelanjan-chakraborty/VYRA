#!/usr/bin/env node
/**
 * Builds the place list used for manual location selection from GeoNames
 * (https://www.geonames.org, CC BY 4.0). Coordinates come only from this
 * dataset — never typed by hand.
 *
 *   node scripts/build-places.mjs
 *
 * Writes packages/validation/src/places-data.ts. Re-run to refresh; commit the result.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

const COUNTRY = 'IN';
const MIN_POPULATION = 100_000;
const BASE = 'https://download.geonames.org/export/dump';
const out = path.resolve(import.meta.dirname, '../packages/validation/src/places-data.ts');
const work = mkdtempSync(path.join(tmpdir(), 'geonames-'));

async function download(name) {
  const response = await fetch(`${BASE}/${name}`);
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
  const file = path.join(work, name);
  writeFileSync(file, Buffer.from(await response.arrayBuffer()));
  return file;
}

try {
  const zip = await download('cities15000.zip');
  const cities = execFileSync('unzip', ['-p', zip, 'cities15000.txt'], {
    maxBuffer: 64 * 1024 * 1024,
  }).toString('utf8');
  const admin1 = readFileSync(await download('admin1CodesASCII.txt'), 'utf8');
  const regions = new Map(
    admin1
      .split('\n')
      .filter(Boolean)
      .map((line) => {
        const [code, name] = line.split('\t');
        return [code, name];
      }),
  );

  const places = cities
    .split('\n')
    .filter(Boolean)
    .map((line) => line.split('\t'))
    .filter((f) => f[8] === COUNTRY && Number(f[14]) >= MIN_POPULATION)
    .map((f) => ({
      id: `gn:${f[0]}`,
      name: f[2], // ASCII name, stable for search
      region: regions.get(`${f[8]}.${f[10]}`) ?? null,
      countryCode: f[8],
      // Two decimals (~1 km) is already finer than VYRA ever stores.
      latitude: Math.round(Number(f[4]) * 100) / 100,
      longitude: Math.round(Number(f[5]) * 100) / 100,
      population: Number(f[14]),
    }))
    .toSorted((a, b) => b.population - a.population);

  const body = [
    '// Generated by scripts/build-places.mjs from GeoNames (https://www.geonames.org), CC BY 4.0.',
    '// Do not edit by hand.',
    "import type { Place } from './location.js';",
    '',
    `export const PLACES_GENERATED_ON = '${new Date().toISOString().slice(0, 10)}';`,
    `export const PLACES: readonly Place[] = ${JSON.stringify(places, null, 0).replaceAll('},{', '},\n  {')};`,
    '',
  ].join('\n');
  writeFileSync(out, body);
  console.log(`Wrote ${places.length} places to ${path.relative(process.cwd(), out)}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
