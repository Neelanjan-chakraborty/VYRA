#!/usr/bin/env node
/**
 * Runs VYRA's real compatibility engine on two synthetic people and writes the
 * result to src/content/engine-sample.json. The website shows these numbers and
 * sentences as an example of what the engine produces, so they must come from
 * the engine and not from a copywriter.
 *
 *   pnpm build && pnpm --filter @vyra/landing engine-sample
 *
 * The two people are invented for this purpose. Nobody's data is involved.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const load = (pkg) =>
  import(new URL(`../../../packages/${pkg}/dist/index.js`, import.meta.url).href);
const engine = await load('compatibility-engine');
const validation = await load('validation');

const WEIGHTS = {
  emotional: 0.25,
  communication: 0.2,
  relationshipAlignment: 0.2,
  lifestyle: 0.15,
  intellectual: 0.1,
  mutualPreferences: 0.1,
};
const DIMENSION_TITLES = {
  emotional: 'Emotional',
  communication: 'Communication',
  relationshipAlignment: 'Relationship alignment',
  lifestyle: 'Lifestyle',
  intellectual: 'Intellectual',
  mutualPreferences: 'Mutual preferences',
};

const trait = (value, confidence) => ({ value, confidence });
const preferences = {
  minAge: 24,
  maxAge: 34,
  maxDistanceKm: null,
  showGenders: [],
  includeUnlistedGenders: true,
  dealBreakers: [],
};
const interest = (slug, label) => ({ slug, label });

/** Person A: described herself and confirmed most of it. */
const a = {
  id: 'synthetic-a',
  age: 28,
  gender: null,
  discoverableAs: [],
  intents: ['serious'],
  preferences,
  location: null,
  traits: {
    socialEnergy: trait(0.25, 0.95),
    emotionalExpressiveness: trait(0.75, 0.95),
    intellectualCuriosity: trait(0.75, 0.6),
    adventureOrientation: trait(0.5, 0.6),
    planningStyle: trait(0.75, 0.95),
    conflictApproach: trait(1, 0.6),
    affectionExpression: trait(0.75, 0.95),
    communicationStyle: trait('reflective', 0.6),
    lifestylePace: trait('balanced', 0.95),
    weekendRhythm: trait('restful', 0.95),
    values: trait(['honesty', 'growth', 'kindness'], 0.95),
  },
  interests: [
    interest('specialty-coffee', 'Specialty coffee'),
    interest('literary-fiction', 'Literary fiction'),
    interest('philosophy', 'Philosophy'),
    interest('illustration', 'Illustration'),
  ],
};

/** Person B: a thinner persona. Weekend rhythm and planning style are unknown. */
const b = {
  id: 'synthetic-b',
  age: 30,
  gender: null,
  discoverableAs: [],
  intents: ['serious', 'exploring'],
  preferences: { ...preferences, minAge: 25, maxAge: 33 },
  location: null,
  traits: {
    socialEnergy: trait(0.75, 0.6),
    emotionalExpressiveness: trait(0.75, 0.6),
    intellectualCuriosity: trait(1, 0.95),
    adventureOrientation: trait(0.75, 0.95),
    conflictApproach: trait(0.75, 0.95),
    affectionExpression: trait(0.5, 0.6),
    communicationStyle: trait('expansive', 0.95),
    lifestylePace: trait('outgoing', 0.6),
    values: trait(['honesty', 'adventure', 'growth'], 0.95),
  },
  interests: [
    interest('specialty-coffee', 'Specialty coffee'),
    interest('philosophy', 'Philosophy'),
    interest('trekking', 'Trekking'),
    interest('photography', 'Photography'),
  ],
};

const ineligible = engine.ineligibility(a, b);
if (ineligible) throw new Error(`The sample pair is not eligible: ${ineligible}`);

const result = engine.score(a, b, WEIGHTS, 'sample-default');
const mirrored = engine.score(b, a, WEIGHTS, 'sample-default');
if (result.overall !== mirrored.overall) throw new Error('The engine should be symmetric.');

const sample = {
  note: 'Generated by apps/landing/scripts/engine-sample.mjs from the real engine. Do not edit by hand.',
  engineVersion: result.engineVersion,
  overall: result.overall,
  confidence: result.confidence,
  sufficiency: result.sufficiency,
  highlights: engine.highlights(result, WEIGHTS),
  sharedInterests: result.sharedInterests,
  dimensions: Object.entries(result.dimensions).map(([key, d]) => ({
    key,
    title: DIMENSION_TITLES[key],
    weight: WEIGHTS[key],
    score: d.score,
    confidence: d.confidence,
    coverage: d.coverage,
    aligned: d.aligned,
    different: d.different,
  })),
  scenarios: result.scenarios.map((s) => ({
    key: s.key,
    title: validation.SCENARIO_TITLES[s.key],
    alignment: s.alignment,
    confidence: s.confidence,
  })),
};

writeFileSync(
  fileURLToPath(new URL('../src/content/engine-sample.json', import.meta.url)),
  `${JSON.stringify(sample, null, 2)}\n`,
);
console.log(JSON.stringify(sample, null, 1));
