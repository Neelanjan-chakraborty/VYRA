#!/usr/bin/env node
/**
 * Writes src/app/tokens.css from the shared design tokens, so the website and
 * the app agree on the neutrals, radii, durations and easings without the site
 * depending on a workspace package at build time (it deploys on its own).
 *
 *   pnpm build                              # builds packages/design-system
 *   pnpm --filter @vyra/landing tokens
 *
 * The website's accent is its own: cherry and oxblood rather than the app's
 * violet (see docs/DECISIONS.md D-043). Every pairing used for text is checked
 * here against WCAG AA with the shared contrast function; the script fails if
 * one does not pass.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ds = await import(
  new URL('../../../packages/design-system/dist/index.js', import.meta.url).href
).catch(() => {
  console.error('Build the design system first: pnpm build');
  process.exit(1);
});
const { palette, radius, duration, easing, contrastRatio } = ds;

const web = {
  cherry: '#D4203A', // fills and large marks
  cherryBright: '#FF5468', // cherry as text on ink
  oxblood: '#5C0F1E', // deep blocks
  oxbloodText: '#8A1528', // cherry as text on ivory
  paper: '#EAE3D9', // second ivory, for rules and tinted panels
  inkSoft: '#57515B', // secondary text on ivory
};

const pairs = [
  ['ivory on ink', palette.ivory, palette.obsidian],
  ['grey on ink', palette.grey, palette.obsidian],
  ['grey on charcoal', palette.grey, palette.charcoal],
  ['cherryBright on ink', web.cherryBright, palette.obsidian],
  ['cherryBright on charcoal', web.cherryBright, palette.charcoal],
  ['ivory on cherry', palette.ivory, web.cherry],
  ['ivory on oxblood', palette.ivory, web.oxblood],
  ['ink on ivory', palette.obsidian, palette.ivory],
  ['inkSoft on ivory', web.inkSoft, palette.ivory],
  ['inkSoft on paper', web.inkSoft, web.paper],
  ['oxbloodText on ivory', web.oxbloodText, palette.ivory],
  ['oxbloodText on paper', web.oxbloodText, web.paper],
];
let failed = false;
for (const [name, fg, bg] of pairs) {
  const ratio = contrastRatio(fg, bg);
  const ok = ratio >= 4.5;
  if (!ok) failed = true;
  console.log(`${ok ? 'ok  ' : 'FAIL'} ${ratio.toFixed(2)}  ${name}`);
}
if (failed) process.exit(1);

const bezier = (points) => `cubic-bezier(${points.join(', ')})`;
const css = `/* Generated by scripts/sync-tokens.mjs from @vyra/design-system. Do not edit by hand. */
:root {
  --vyra-ink: ${palette.obsidian};
  --vyra-ink-raised: ${palette.charcoal};
  --vyra-ink-high: ${palette.charcoalRaised};
  --vyra-hairline: ${palette.hairline};
  --vyra-ivory: ${palette.ivory};
  --vyra-grey: ${palette.grey};
  --vyra-app-violet: ${palette.violet};

  --vyra-cherry: ${web.cherry};
  --vyra-cherry-bright: ${web.cherryBright};
  --vyra-oxblood: ${web.oxblood};
  --vyra-oxblood-text: ${web.oxbloodText};
  --vyra-paper: ${web.paper};
  --vyra-ink-soft: ${web.inkSoft};

  --vyra-radius-s: ${radius.s}px;
  --vyra-radius-m: ${radius.m}px;
  --vyra-radius-l: ${radius.l}px;

  --vyra-duration-fast: ${duration.fast}ms;
  --vyra-duration-base: ${duration.base}ms;
  --vyra-duration-slow: ${duration.slow}ms;
  --vyra-duration-cinematic: ${duration.cinematic}ms;
  --vyra-ease-standard: ${bezier(easing.standard)};
  --vyra-ease-enter: ${bezier(easing.enter)};
  --vyra-ease-exit: ${bezier(easing.exit)};
}
`;
writeFileSync(fileURLToPath(new URL('../src/app/tokens.css', import.meta.url)), css);
console.log('Wrote src/app/tokens.css');
