#!/usr/bin/env node
/**
 * Converts the licensed icon SVGs into src/lib/icon-data.ts: plain data that
 * the <Icon> component renders as inline SVG in `currentColor`.
 *
 *   node scripts/build-icons.mjs <directory with the original i<id>.svg files>
 *
 * Third-party SVG is never inlined as markup. Only a short list of shape
 * elements and presentation attributes is kept; scripts, styles, links,
 * images, gradients and clip paths are dropped, and every colour becomes
 * `currentColor` so one icon can sit on ink, ivory or cherry.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'node-html-parser';

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/build-icons.mjs <directory of originals>');
  process.exit(2);
}

/** name → [stock id, author, what it stands for] */
const icons = {
  persona: ['17112699', 'hari-sabana'],
  compatibility: ['18032175', 'Iconir'],
  privacy: ['5752368', 'yaicon'],
  chat: ['18866229', 'Nur syifa fauziah'],
  ai: ['10795304', 'Magnific'],
  photo: ['10424647', 'afif fudin'],
  location: ['16313827', 'prinda895'],
};

const SHAPES = new Set(['g', 'path', 'circle', 'ellipse', 'rect', 'line', 'polyline', 'polygon']);
const ATTRS = new Set([
  'd',
  'cx',
  'cy',
  'r',
  'rx',
  'ry',
  'x',
  'y',
  'x1',
  'x2',
  'y1',
  'y2',
  'width',
  'height',
  'points',
  'transform',
  'fill',
  'stroke',
  'stroke-width',
  'stroke-linecap',
  'stroke-linejoin',
  'stroke-miterlimit',
  'fill-rule',
  'clip-rule',
  'opacity',
  'fill-opacity',
  'stroke-opacity',
]);
const PRESENTATION = new Set(
  [...ATTRS].filter((a) => !/^(d|c[xy]|r[xy]?|[xy][12]?|width|height|points|transform)$/.test(a)),
);

const colour = (value) => {
  const v = value.trim().toLowerCase();
  if (v === 'none' || v === 'transparent') return 'none';
  return 'currentColor'; // #000, #000000, black, url(#gradient) … all become the text colour
};

function convert(node) {
  const tag = node.rawTagName?.toLowerCase();
  if (!tag || !SHAPES.has(tag)) return null;
  const attrs = {};
  const raw = { ...node.attributes };
  // `style="fill:none;stroke:#000;stroke-width:20"` → presentation attributes.
  for (const declaration of (raw.style ?? '').split(';')) {
    const [name, ...rest] = declaration.split(':');
    if (name && rest.length && PRESENTATION.has(name.trim()))
      raw[name.trim()] = rest.join(':').trim();
  }
  for (const [name, value] of Object.entries(raw)) {
    if (!ATTRS.has(name)) continue;
    attrs[name] = name === 'fill' || name === 'stroke' ? colour(value) : value;
  }
  const children = node.childNodes.map(convert).filter(Boolean);
  return children.length > 0 ? { tag, attrs, children } : { tag, attrs };
}

const data = {};
for (const [name, [id, author]] of Object.entries(icons)) {
  const svg = parse(readFileSync(join(source, `i${id}.svg`), 'utf8')).querySelector('svg');
  if (!svg) throw new Error(`${name}: no <svg> element`);
  const viewBox = svg.getAttribute('viewBox');
  if (!viewBox) throw new Error(`${name}: no viewBox`);
  const nodes = svg.childNodes.map(convert).filter(Boolean);
  const rootFill = svg.getAttribute('fill');
  const hasOwnFill = JSON.stringify(nodes).includes('"fill"');
  data[name] = {
    id: Number(id),
    author,
    viewBox,
    // Icons drawn as filled outlines need a fill; stroke icons set their own.
    fill: rootFill === 'none' || hasOwnFill ? 'none' : 'currentColor',
    nodes,
  };
  console.log(`${name}: ${JSON.stringify(nodes).length} bytes`);
}

const body = `// Generated by scripts/build-icons.mjs. Do not edit by hand.\n// Icons: Magnific / Flaticon, credited per icon in src/content/photos.ts.\nexport interface IconNode {\n  readonly tag: string;\n  readonly attrs: Readonly<Record<string, string>>;\n  readonly children?: readonly IconNode[];\n}\nexport interface IconData {\n  readonly id: number;\n  readonly author: string;\n  readonly viewBox: string;\n  readonly fill: 'none' | 'currentColor';\n  readonly nodes: readonly IconNode[];\n}\nexport const iconData = ${JSON.stringify(data, null, 2)} as const satisfies Record<string, IconData>;\nexport type IconName = keyof typeof iconData;\n`;
writeFileSync(fileURLToPath(new URL('../src/lib/icon-data.ts', import.meta.url)), body);
